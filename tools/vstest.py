from pathlib import Path
from unicorn.x86_const import *
import engineering_vs,engineering3840,d01test
v=engineering3840.load_private();out=[]
for path in sys.argv[1:3]:
 raw=Path(path).read_bytes();data,meta=engineering_vs.build(raw);again,_=engineering_vs.build(raw);assert data==again

 baseline_build=v.BUILDS[hashlib.md5(raw).hexdigest()]
 wanted=dict.fromkeys(v.by_key(baseline_build),True);wanted['hires']=(3840,1080)
 baseline,_,skipped=v.apply_selected(bytearray(raw),wanted,baseline_build);assert not skipped
 original_pe=v._PE(baseline);ui_section=next(x for x in original_pe.sections if x['name']==b'.vohr')
 allowed=set(range(min(x['raddr'] for x in original_pe.sections if x['raddr'])))
 allowed.update(range(ui_section['raddr']+v.UI_KSBS,ui_section['raddr']+v.UI_KSBS+4))
 for marker in meta['markers']:
  off=original_pe.off(marker['entry']-original_pe.base);allowed.update(range(off,off+9))
 port=None if meta['edition']=='retail' else v.PORT['%08x'%v._pe_stamp(raw)]
 off=0x1c751b if port is None else port['off'][0x1c751b][0];allowed.update(range(off,off+5))
 assert all(i in allowed for i,(a,b_) in enumerate(zip(baseline,data)) if a!=b_), 'unrelated generated bytes changed'
 mu,pe=d01test.image(data)
 def put(a,n):mu.mem_write(a,struct.pack('<I',n&0xffffffff))
 def get(a):return struct.unpack('<I',mu.mem_read(a,4))[0]
 def call(entry,stop):
  mu.reg_write(UC_X86_REG_ESP,d01test.STACK+0x8000);mu.emu_start(entry,stop,count=10000);assert mu.reg_read(UC_X86_REG_EIP)==stop
 regs=[UC_X86_REG_EAX,UC_X86_REG_EBX,UC_X86_REG_ECX,UC_X86_REG_EDX,UC_X86_REG_ESI,UC_X86_REG_EDI,UC_X86_REG_EBP]
 count=0
 for marker in meta['markers']:
  # Stop before replayed original prologue to check preserved registers/flags/stack.
  code=bytes(mu.mem_read(marker['stub'],500));at=code.index(bytes.fromhex(marker['displaced']));stop=marker['stub']+at
  for mode1,mode2 in ((4,4),(1,4),(4,1)):
   for s1 in range(66):
    for s2 in (0,9,10,20,32,65):
     for split,flags in ((0,0),(1,0),(1,2)):
      states=dict(mode1=mode1,mode2=mode2,sub1=s1,sub2=s2,split=split,flags=flags)
      for k,value in states.items():put(meta['state'][k],value)
      # Poison the cached show selection: implementation must read current state.
      put(meta['ui']+0x1e88,2)
      for r in regs:mu.reg_write(r,0x12345678)
      mu.reg_write(UC_X86_REG_EFLAGS,0x202)
      call(marker['entry'],stop)
      assert all(mu.reg_read(r)==0x12345678 for r in regs)
      assert mu.reg_read(UC_X86_REG_ESP)==d01test.STACK+0x8000
      assert mu.reg_read(UC_X86_REG_EFLAGS)==0x202
      narrow=split and not(flags&1) and mode1==4 and (s1 in v.HIRES_SPLIT_STATES or (mode2==4 and s2 in v.HIRES_SPLIT_STATES))
      assert [get(a) for a,_,_ in marker['fields']]==[half if narrow else full for a,full,half in marker['fields']]
      count+=1
  # F4 alternate mode must retain that mode's installed operands.
  put(meta['ui']+v.UI_MODEW,1280)
  for a,_,_ in marker['fields']:put(a,0x1234)
  call(marker['entry'],stop);assert all(get(a)==0x1234 for a,_,_ in marker['fields'])
  put(meta['ui']+v.UI_MODEW,3840)
 # Execute the original frame wrapper through the private layout shim.
 port=None if meta['edition']=='retail' else v.PORT['%08x'%v._pe_stamp(raw)]
 address=lambda a:a if port is None else port['va'][a]
 desc=d01test.STACK+0x1000;put(desc+0x24,0x10000000);put(desc+0x10,7744)
 for sub,expected_width,expected_show in ((0,3840,1),(9,1920,0),(32,3840,1),(10,1920,0)):
  for key,value in dict(mode1=4,mode2=4,sub1=sub,sub2=sub,split=1,flags=2).items():put(meta['state'][key],value)
  sp=d01test.STACK+0x8000;put(sp,d01test.RET);put(sp+4,desc)
  call(meta['frame'],d01test.RET)
  assert get(address(v.ADDR['FB_W']))==expected_width
  assert get(meta['ui']+0x1e88)==expected_show
  if expected_show==0:
   assert get(address(0x6bf5b0))-get(address(0x6bf5a8))==3840
   assert struct.unpack('<f',mu.mem_read(address(v.ADDR['SCALE_A']),4))[0]==2.25
   assert struct.unpack('<f',mu.mem_read(address(v.ADDR['SCALE_B']),4))[0]==2.25
 # Existing compositor must isolate distinct HUD pixels in the actual VS image.
 import uibuild
 saved=list(uibuild.LABELS);uibuild.LABELS += ['set1post','set2post']
 blob,labels=uibuild.assemble((Path(__file__).resolve().parents[1]/'asm/ui.asm').read_text());uibuild.LABELS=saved
 assert blob==v.UI_CODE
 surface=0x10000000;mu.mem_map(surface,0xa00000)
 initial=b'\x17\x29'*(7744*1080//2);mu.mem_write(surface,initial)
 def routine(name):
  sp=d01test.STACK+0x8000;put(sp,d01test.RET);mu.reg_write(UC_X86_REG_ESP,sp)
  mu.emu_start(meta['ui']+labels[name],d01test.RET,count=60000000)
  assert mu.reg_read(UC_X86_REG_EIP)==d01test.RET
 for player,name in ((1,'set1post'),(2,'set2post')):
  before=bytes(mu.mem_read(surface,len(initial)));routine(name);routine('pre')
  assert get(meta['ui']+0x1cc8)==147456 and get(meta['ui']+0x1c34)==240
  mu.mem_write(meta['ui']+v.UI_CANVAS_OFF+240*v.UI_CANVAS_PITCH+320*2,struct.pack('<H',0x1111*player))
  routine('post');after=bytes(mu.mem_read(surface,len(initial)))
  changed=[i for i,(x,y) in enumerate(zip(before,after)) if x!=y];assert changed
  assert all((player-1)*3840<=i%7744<player*3840 for i in changed)
 out.append(dict(edition=meta['edition'],transitions=count,deterministic=True,sha256=hashlib.sha256(data).hexdigest()))
print(json.dumps(out,indent=2))
