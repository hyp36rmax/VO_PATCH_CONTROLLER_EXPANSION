"""Dedicated VS primary F4 restore, on pristine Retail/JPRE input directories.

This proves table roundtrips, not live Windows presentation compatibility.
"""
import hashlib
from pathlib import Path
import struct
import sys
import mode_profiles

v = mode_profiles.engineering3840.load_private()
for folder in map(Path, sys.argv[1:]):
    data, meta = mode_profiles.build((folder / 'v_on.exe').read_bytes(), 'dual')
    pe = v._PE(data)
    ui = next(s for s in pe.sections if s['name'] == b'.vohr')
    cursor = pe.off(struct.unpack_from('<I', data, ui['raddr'] + v.UI_F4TAB)[0] - pe.base)
    records = []
    while True:
        address, size = struct.unpack_from('<II', data, cursor)
        if not address:
            break
        offset = pe.off(address - pe.base)
        a = data[cursor + 8:cursor + 8 + size]
        b = data[cursor + 8 + size:cursor + 8 + 2 * size]
        assert data[offset:offset + size] == a, hex(address)
        records.append((offset, a, b))
        cursor += 8 + 2 * size
    changed = bytearray(data)
    for offset, a, b in records:
        changed[offset:offset + len(b)] = b
    assert struct.unpack_from('<II', changed, ui['raddr'] + v.UI_MODEW) == (1280, 720)
    for offset, a, b in records:
        changed[offset:offset + len(a)] = a
    assert changed == data, 'roundtrip must restore every generated byte'
    assert struct.unpack_from('<f', changed, ui['raddr'] + v.UI_KSBS)[0] == 1.0
    print('PASS', meta['edition'], 'dedicated VS table roundtrip and split factor', hashlib.sha256(data).hexdigest())
