"""Generate a bounded read-only identity/address table from verified VS images."""
import sys,struct
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import engineering_shared,engineering3840
v=engineering3840.load_private();rows=[]
for name in sys.argv[1:3]:
 raw=Path(name).read_bytes();data,m=engineering_shared.build(raw);pe=v._PE(data)
 port=None if m['edition']=='retail' else v.PORT['%08x'%v._pe_stamp(raw)]
 loop=0x6bc94c if port is None else port['va'][0x6bc94c]
 nt=struct.unpack_from('<I',data,0x3c)[0];size=struct.unpack_from('<I',data,nt+24+56)[0]
 sig=m['shared']['signature'];off=pe.off(sig-pe.base);signature=data[off:off+32]
 rows.append('{'+','.join(hex(x) for x in (pe.base,v._pe_stamp(raw),size,sig,loop,m['state']['mode1'],m['state']['split'],m['ui']+0x1e88))+',{'+','.join(hex(b) for b in signature)+'}}')
Path(sys.argv[3]).write_text('/* Generated by build_profiles.py from Retail/JPRE private VS images. */\n#include <stdint.h>\ntypedef struct {uintptr_t base;unsigned stamp,size;uintptr_t signature,loop,mode,split,show;unsigned char bytes[32];} VoGameProfile;\nstatic const VoGameProfile vo_profiles[]={\n'+',\n'.join(rows)+'\n};\n')
